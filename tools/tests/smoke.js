const { chromium } = require('playwright');
const EXE = process.env.CHROME || undefined;
(async () => {
  const b = await chromium.launch({ executablePath: EXE, args: ['--no-sandbox'] });
  const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
  const errors = [];
  p.on('console', m => { if (m.type()==='error' || m.type()==='warning') errors.push(m.type()+': '+m.text()); });
  p.on('pageerror', e => errors.push('PAGEERROR: ' + e.message));
  await p.goto('http://127.0.0.1:8822/index.html');
  await p.waitForTimeout(500);
  const vis = async () => (await p.$$eval('main > .screen', els => els.filter(e => !e.hidden).map(e => e.id))).join(',');
  console.log('screen:', await vis());
  await p.click('#btn-start'); console.log('screen:', await vis());
  await p.click('#domain-grid button:nth-child(4)'); console.log('screen:', await vis());
  await p.click('#btn-mode-data'); console.log('screen:', await vis());
  await p.click('#btn-data-starter');
  console.log('count:', await p.textContent('#data-count'));
  await p.click('#btn-data-train'); await p.waitForTimeout(1800); console.log('screen:', await vis());
  console.log('meter:', await p.textContent('#meter-say'), '|', await p.textContent('#data-evidence'));
  await p.click('#btn-data-to-break'); console.log('screen:', await vis());
  // set the hot-but-calm trap: temp 110, vib 1.5
  await p.fill('#field-break-x-x-num', '110'); await p.dispatchEvent('#field-break-x-x-num', 'change');
  await p.fill('#field-break-y-y-num', '1.5'); await p.dispatchEvent('#field-break-y-y-num', 'change');
  await p.waitForTimeout(200);
  console.log('meter@trap:', await p.textContent('#meter-say'), '|', await p.textContent('#data-break-evidence'));
  await p.click('#btn-data-declare-fail'); console.log('screen:', await vis());
  console.log('understand:', await p.textContent('#understand-snapshot'));
  await p.click('#reason-chips button:nth-child(2)'); console.log('reflection:', await p.textContent('#reason-reflection'));
  await p.click('#btn-to-improve'); console.log('screen:', await vis());
  console.log('improve point:', await p.textContent('#data-improve-point'));
  await p.click('#btn-data-improve-1'); await p.click('#btn-data-retrain'); await p.waitForTimeout(1800);
  console.log('result:', await p.textContent('#data-improve-result'));
  await p.click('#btn-data-better'); console.log('screen:', await vis());
  console.log('concepts:', await p.$$eval('#concepts .concept', els => els.map(e => e.textContent.trim()).join(' | ')));
  await p.click('#btn-to-connect'); console.log('screen:', await vis());
  console.log('belong:', await p.textContent('#h-connect'));
  await p.fill('#idea-input', 'predict flooding in small towns'); await p.click('#btn-make-challenge'); await p.waitForTimeout(300);
  console.log('card:', (await p.textContent('#challenge-card')).slice(0, 400));
  await p.click('#btn-to-finish'); console.log('screen:', await vis());
  console.log('finish h1:', await p.textContent('#h-finish'), '| tally:', await p.textContent('#tally'));
  await p.click('#btn-finish-reset'); console.log('screen after reset:', await vis());
  console.log('ERRORS:', errors);
  await b.close();
})().catch(e => { console.error('ERR', e); process.exit(1); });
